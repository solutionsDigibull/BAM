"""#817: the dev web node_modules volume follows the image's lockfile instead of going stale."""

import shutil
import subprocess
from pathlib import Path
from typing import Any

import pytest
import yaml

REPO = Path(__file__).resolve().parents[3]
SCRIPT = REPO / "compose/docker/web/refresh-node-modules.sh"
needs_sh = pytest.mark.skipif(
    shutil.which("sh") is None or shutil.which("sha256sum") is None, reason="needs sh and sha256sum"
)


class _ComposeLoader(yaml.SafeLoader):
    """A safe loader that also reads Compose's `!reset` tag (used by the override file)."""


_ComposeLoader.add_constructor("!reset", lambda loader, node: None)


def override() -> dict[str, Any]:
    text = (REPO / "compose/compose.override.yaml").read_text("utf-8")
    data: dict[str, Any] = yaml.load(text, Loader=_ComposeLoader)  # noqa: S506
    return data


def make_tree(tmp_path: Path, lock: str, packages: list[str]) -> tuple[Path, Path, Path]:
    app = tmp_path / "app"
    src = app / "node_modules"
    for name in packages:
        (src / name).mkdir(parents=True)
        (src / name / "index.js").write_text(name, "utf-8")
    (src / ".pnpm").mkdir()
    (app / "pnpm-lock.yaml").write_text(lock, "utf-8")
    dst = tmp_path / "nm"
    dst.mkdir()
    return app / "pnpm-lock.yaml", src, dst


def refresh(lock: Path, src: Path, dst: Path) -> str:
    env = {"LOCK": str(lock), "SRC": str(src), "DST": str(dst), "PATH": "/usr/bin:/bin"}
    done = subprocess.run(  # noqa: S603 - fixed argv
        ["sh", str(SCRIPT)],  # noqa: S607
        env=env,
        capture_output=True,
        text=True,
        check=True,
    )
    return done.stdout


@needs_sh
def test_817_an_empty_or_old_volume_gets_the_image_node_modules(tmp_path: Path) -> None:
    lock, src, dst = make_tree(tmp_path, "lock-v2", ["d3-force", "react"])
    (dst / "react").mkdir()  # a volume made from an older image: no d3-force
    out = refresh(lock, src, dst)
    assert "refreshing" in out
    assert (dst / "d3-force" / "index.js").read_text("utf-8") == "d3-force"
    assert (dst / ".pnpm").is_dir()  # hidden entries come along
    assert (dst / ".sbam-lock-sha").read_text("utf-8").strip()


@needs_sh
def test_817_an_unchanged_lockfile_copies_nothing(tmp_path: Path) -> None:
    lock, src, dst = make_tree(tmp_path, "lock-v1", ["react"])
    refresh(lock, src, dst)
    (dst / "react" / "marker").write_text("untouched", "utf-8")
    assert "current" in refresh(lock, src, dst)
    assert (dst / "react" / "marker").exists()  # a refresh would have replaced the directory


@needs_sh
def test_817_a_changed_lockfile_replaces_the_content_and_drops_a_stale_package(
    tmp_path: Path,
) -> None:
    lock, src, dst = make_tree(tmp_path, "lock-v1", ["react", "old-lib"])
    refresh(lock, src, dst)
    shutil.rmtree(src / "old-lib")  # the new image no longer has it
    (src / "d3-force").mkdir()
    lock.write_text("lock-v2", "utf-8")
    assert "refreshing" in refresh(lock, src, dst)
    assert not (dst / "old-lib").exists()
    assert (dst / "d3-force").is_dir()


def test_817_web_waits_for_the_refresh_and_it_uses_the_same_volume() -> None:
    services = override()["services"]
    deps = services["web-deps"]
    assert deps["image"] == "sbam-web:local"
    assert "web_node_modules:/nm" in deps["volumes"]
    assert deps["entrypoint"] == ["sh", "/refresh-node-modules.sh"]
    assert services["sbam-web"]["depends_on"]["web-deps"] == {
        "condition": "service_completed_successfully"
    }
    assert "web_node_modules:/app/client/node_modules" in services["sbam-web"]["volumes"]
