# --- T06 / T07: TypeScript quality ----------------------------------------------------------------


def test_e1_2_t06_no_any_in_the_generated_typescript(ts: str) -> None:
    assert re.findall(r":\s*any\b|<any>|\bany\[\]|as any\b", ts) == []


def test_e1_2_header_says_generated_and_carries_the_source_hash(ts: str) -> None:
    assert ts.startswith("// GENERATED — DO NOT EDIT.")
    assert f"// source-{sha256_of(ts_bundle())}\n" in ts


def test_e1_2_t07_skill_manifest_version_pattern_and_enum_unions(ts: str) -> None:
    meta = interface(ts, "SbamSkillMetadata")
    assert "Pattern: `^\\d+\\.0\\.\\d+$`" in meta
    assert "  status: ManifestStatus;" in meta
    assert '  skill_type: "Deterministic_Loopy_MCP";' in meta
    assert re.search(
        r'export type ManifestStatus = "DRAFT" \| "VALIDATING" \| "APPROVED" \| "SUPERSEDED";', ts
    )
    assert re.search(r'export type ErrorCode =\n  \| "VALIDATION_ERROR"', ts)


@pytest.mark.parametrize(("path", "model"), ROOTS, ids=[p for p, _ in ROOTS])
def test_e1_2_every_root_field_is_in_its_typescript_interface(
    ts: str, path: str, model: type[BaseModel]
) -> None:
    block = interface(ts, model.__name__)
    for name in committed_schema(path)["properties"]:
        key = re.escape(name) if name.isidentifier() else re.escape(json.dumps(name))
        assert re.search(rf"^  {key}\??:", block, re.MULTILINE), f"{model.__name__}.{name}"
