TS_GENERATOR = REPO / "client" / "node_modules" / "json-schema-to-typescript"
pytestmark = pytest.mark.skipif(
    shutil.which("node") is None or not TS_GENERATOR.exists(),
    reason="needs Node and `pnpm --dir client install` (always present in the CI drift job)",
)
TS_RELATIVE = "client/src/contracts/index.ts"
SOW_SCHEMA = "server/contracts/schemas/sow/sow_document.schema.json"


@pytest.fixture(scope="module")
def generated() -> dict[Path, bytes]:
    return generate()


@pytest.fixture(scope="module")
def ts(generated: dict[Path, bytes]) -> str:
    return generated[TS_FILE].decode("utf-8")


def mirror(files: dict[Path, bytes], root: Path) -> Path:
    """Copy the committed generated files into `root`, at the same relative paths."""
    for path in files:
        target = root / path.relative_to(REPO)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
    return root


def interface(ts: str, name: str) -> str:
    match = re.search(rf"^export interface {name} \{{\n(.*?)^\}}", ts, re.MULTILINE | re.DOTALL)
    assert match, f"no interface {name} in the generated TypeScript"
    return match.group(1)


def committed_schema(path: str) -> dict[str, Any]:
    data = json.loads((SCHEMA_DIR / f"{path}.schema.json").read_text(encoding="utf-8"))
    assert isinstance(data, dict)
    return data


# --- T01 / T04: clean and deterministic -----------------------------------------------------------


def test_e1_2_t01_generation_matches_the_committed_files(generated: dict[Path, bytes]) -> None:
    assert drift(generated) == [], "run `make contracts` and commit the result"


